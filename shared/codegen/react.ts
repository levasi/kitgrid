import { findDescendant } from '../document/tree'
import { pathData } from '../document/path'
import type { ComponentDefinition, DesignDocument, DesignNode, DesignTokens, Page } from '../document/types'
import { isContainer } from '../document/types'
import { resolvedSpacing, resolvedTypography } from '../document/paint'

export interface GeneratedCode {
  react: string
  css: string
}

export function generateReact(doc: DesignDocument, pageId: string): GeneratedCode {
  const page = doc.pages.find(item => item.id === pageId)
  if (!page) throw new Error('Page not found.')
  const used = componentsUsed(page, doc)
  const names = new Map<string, string>()
  const taken = new Set<string>()
  for (const component of used) {
    names.set(component.id, uniqueIdentifier(component.name, 'Component', taken))
  }
  let pageName = uniqueIdentifier(page.name, 'Page', new Set(names.values()))
  if (taken.has(pageName)) pageName = uniqueIdentifier(`${page.name} page`, 'Page', taken)

  const react = [
    '// Generated by Tessera from the design document.',
    "import React from 'react'",
    '',
    ...used.map(component => renderComponent(component, names.get(component.id) ?? 'Component', doc.tokens)),
    renderPage(page, pageName, doc, names),
  ].filter(part => part !== '').join('\n\n')

  const css = [
    renderTokens(doc.tokens),
    ...used.map(component => renderComponentCss(component, doc.tokens)),
    renderPageCss(page, doc),
  ].filter(Boolean).join('\n\n')

  return { react: `${react}\n`, css: `${css}\n` }
}

function componentsUsed(page: Page, doc: DesignDocument): ComponentDefinition[] {
  const ids = new Set<string>()
  const visit = (node: DesignNode) => {
    if (node.type === 'instance') ids.add(node.componentId)
    if (isContainer(node)) node.children.forEach(visit)
  }
  page.children.forEach(visit)
  let grew = true
  while (grew) {
    const before = ids.size
    for (const component of doc.components) {
      if (!ids.has(component.id)) continue
      visit(component.root)
    }
    grew = ids.size !== before
  }
  return doc.components.filter(component => ids.has(component.id))
}

function renderComponent(component: ComponentDefinition, functionName: string, tokens: DesignTokens): string {
  const variants = component.variants.options.map(option => `'${option.id}'`).join(' | ')
  const labelDefault = JSON.stringify(component.label.defaultValue)
  const variantDefault = JSON.stringify(component.variants.defaultVariantId)
  const extras = component.root.children
    .filter(child => child.id !== component.label.targetNodeId)
    .map(child => renderElement(child, tokens, 6))
    .join('\n')
  return [
    `export function ${functionName}({`,
    `  label = ${labelDefault},`,
    `  variant = ${variantDefault},`,
    '  className,',
    '}: {',
    '  label?: string',
    `  variant?: ${variants}`,
    '  className?: string',
    '}) {',
    '  return (',
    `    <div className={['${componentClass(component.id)}', \`is-\${variant}\`, className].filter(Boolean).join(' ')}>`,
    `      <span className="${componentClass(component.id)}__label">{label}</span>`,
    extras,
    '    </div>',
    '  )',
    '}',
  ].filter(line => line !== '').join('\n')
}

function renderPage(page: Page, functionName: string, doc: DesignDocument, names: Map<string, string>): string {
  const body = page.children.map(child => renderElement(child, doc.tokens, 4, names)).join('\n')
  return [
    `export function ${functionName}() {`,
    '  return (',
    `    <div className="page ${pageClass(page.id)}">`,
    body,
    '    </div>',
    '  )',
    '}',
  ].join('\n')
}

function renderElement(node: DesignNode, tokens: DesignTokens, indent: number, names?: Map<string, string>): string {
  const pad = ' '.repeat(indent)
  if (!node.visible) return ''
  if (node.type === 'instance') {
    const functionName = names?.get(node.componentId) ?? 'MissingComponent'
    const label = node.overrides.label
    const variant = node.overrides.variant
    const props = [`className="${nodeClass(node.id)}"`]
    if (label !== undefined) props.push(`label={${JSON.stringify(label)}}`)
    if (variant !== undefined) props.push(`variant="${variant}"`)
    return `${pad}<${functionName} ${props.join(' ')} />`
  }
  if (node.type === 'path') {
    const fill = node.fill === 'none' && !node.fillTokenId ? 'none' : colorCss(tokens, node.fill, node.fillTokenId)
    const stroke = colorCss(tokens, node.stroke, node.strokeTokenId)
    return `${pad}<svg className="${nodeClass(node.id)}" viewBox="0 0 ${node.width} ${node.height}"><path d="${pathData(node.points, node.closed)}" fill="${fill}" stroke="${stroke}" strokeWidth={${node.strokeWidth}} strokeLinecap="round" strokeLinejoin="round" /></svg>`
  }
  const tag = node.type === 'text' ? 'p' : 'div'
  const children = isContainer(node)
    ? node.children.map(child => renderElement(child, tokens, indent + 2, names)).filter(Boolean)
    : []
  if (node.type === 'text') {
    return `${pad}<${tag} className="${nodeClass(node.id)}">{${JSON.stringify(node.content)}}</${tag}>`
  }
  if (children.length === 0) return `${pad}<${tag} className="${nodeClass(node.id)}" />`
  return [
    `${pad}<${tag} className="${nodeClass(node.id)}">`,
    ...children,
    `${pad}</${tag}>`,
  ].join('\n')
}

function renderTokens(tokens: DesignTokens): string {
  const lines = [
    ...tokens.colors.map(token => `  ${cssVar(token.id)}: ${token.value};`),
    ...tokens.spacing.map(token => `  ${cssVar(token.id)}: ${token.value}px;`),
    ...tokens.typography.flatMap(token => [
      `  ${cssVar(token.id)}-font-family: ${token.fontFamily};`,
      `  ${cssVar(token.id)}-font-size: ${token.fontSize}px;`,
      `  ${cssVar(token.id)}-font-weight: ${token.fontWeight};`,
      `  ${cssVar(token.id)}-line-height: ${token.lineHeight};`,
    ]),
  ]
  return `:root {\n${lines.join('\n')}\n}`
}

function renderComponentCss(component: ComponentDefinition, tokens: DesignTokens): string {
  const label = findDescendant(component.root, component.label.targetNodeId)
  const type = label?.type === 'text' ? resolvedTypography(label, tokens) : null
  const rules = [
    rule(`.${componentClass(component.id)}`, {
      position: 'relative',
      width: '100%',
      height: '100%',
      'box-sizing': 'border-box',
      overflow: component.root.clip ? 'hidden' : 'visible',
      padding: `${resolvedSpacing(tokens, component.root.padding, component.root.paddingTokenId)}px`,
    }),
    ...component.variants.options.map(option => rule(`.${componentClass(component.id)}.is-${option.id}`, {
      background: colorCss(tokens, option.style.fill, option.style.fillTokenId),
      color: colorCss(tokens, option.style.textColor, option.style.textColorTokenId),
      'border-radius': `${option.style.radius}px`,
      border: option.style.strokeWidth > 0
        ? `${option.style.strokeWidth}px solid ${colorCss(tokens, option.style.stroke, option.style.strokeTokenId)}`
        : 'none',
    })),
    rule(`.${componentClass(component.id)}__label`, {
      position: 'absolute',
      inset: '0',
      display: 'flex',
      'align-items': label?.type === 'text' && label.verticalAlign === 'middle' ? 'center' : 'flex-start',
      'justify-content': label?.type === 'text' && label.align === 'center' ? 'center' : label?.type === 'text' && label.align === 'right' ? 'flex-end' : 'flex-start',
      'font-family': type ? fontFamilyCss(label?.type === 'text' ? label : null, tokens) : 'inherit',
      'font-size': type ? fontSizeCss(label?.type === 'text' ? label : null, tokens) : 'inherit',
      'font-weight': type ? fontWeightCss(label?.type === 'text' ? label : null, tokens) : 'inherit',
      'line-height': type ? lineHeightCss(label?.type === 'text' ? label : null, tokens) : 'inherit',
      'white-space': 'pre-wrap',
    }),
  ]
  for (const child of component.root.children) {
    if (child.id === component.label.targetNodeId) continue
    rules.push(...nodeRules(child, tokens, false))
  }
  return rules.join('\n\n')
}

function renderPageCss(page: Page, doc: DesignDocument): string {
  const rules = [
    rule(`.${pageClass(page.id)}`, {
      position: 'relative',
      width: `${page.width}px`,
      height: `${page.height}px`,
      background: '#f4f4f5',
      overflow: 'hidden',
    }),
  ]
  const visit = (node: DesignNode) => {
    rules.push(...nodeRules(node, doc.tokens, node.type === 'instance'))
    if (node.type === 'instance') return
    if (isContainer(node)) node.children.forEach(visit)
  }
  page.children.forEach(visit)
  return rules.join('\n\n')
}

function nodeRules(node: DesignNode, tokens: DesignTokens, geometryOnly: boolean): string[] {
  const geometry: Record<string, string> = {
    position: 'absolute',
    left: `${node.x}px`,
    top: `${node.y}px`,
    width: `${node.width}px`,
    height: `${node.height}px`,
    'box-sizing': 'border-box',
  }
  if (geometryOnly || !node.visible) return [rule(`.${nodeClass(node.id)}`, geometry)]
  if (node.type === 'text') {
    return [rule(`.${nodeClass(node.id)}`, {
      ...geometry,
      display: 'flex',
      'align-items': node.verticalAlign === 'middle' ? 'center' : 'flex-start',
      'justify-content': node.align === 'center' ? 'center' : node.align === 'right' ? 'flex-end' : 'flex-start',
      margin: '0',
      overflow: 'hidden',
      color: colorCss(tokens, node.color, node.colorTokenId),
      'font-family': fontFamilyCss(node, tokens),
      'font-size': fontSizeCss(node, tokens),
      'font-weight': fontWeightCss(node, tokens),
      'line-height': lineHeightCss(node, tokens),
      'white-space': 'pre-wrap',
    })]
  }
  if (node.type === 'rectangle' || node.type === 'frame') {
    const paint: Record<string, string> = {
      ...geometry,
      background: colorCss(tokens, node.fill, node.fillTokenId),
      'border-radius': `${node.radius}px`,
      border: node.strokeWidth > 0
        ? `${node.strokeWidth}px solid ${colorCss(tokens, node.stroke, node.strokeTokenId)}`
        : 'none',
      overflow: node.type === 'frame' ? (node.clip ? 'hidden' : 'visible') : 'hidden',
    }
    if (node.type === 'frame') {
      paint.padding = `${resolvedSpacing(tokens, node.padding, node.paddingTokenId)}px`
      if (node.direction !== 'none') {
        paint.display = 'flex'
        paint['flex-direction'] = node.direction === 'horizontal' ? 'row' : 'column'
        paint.gap = `${resolvedSpacing(tokens, node.gap, node.gapTokenId)}px`
      }
    }
    return [rule(`.${nodeClass(node.id)}`, paint)]
  }
  return [rule(`.${nodeClass(node.id)}`, { ...geometry, overflow: 'visible' })]
}

function fontFamilyCss(node: DesignNode | null, tokens: DesignTokens): string {
  if (node?.type === 'text' && node.typographyTokenId && tokens.typography.some(token => token.id === node.typographyTokenId)) {
    return `var(${cssVar(node.typographyTokenId)}-font-family)`
  }
  return node?.type === 'text' ? node.fontFamily : 'inherit'
}

function fontSizeCss(node: DesignNode | null, tokens: DesignTokens): string {
  if (node?.type === 'text' && node.typographyTokenId && tokens.typography.some(token => token.id === node.typographyTokenId)) {
    return `var(${cssVar(node.typographyTokenId)}-font-size)`
  }
  return node?.type === 'text' ? `${node.fontSize}px` : 'inherit'
}

function fontWeightCss(node: DesignNode | null, tokens: DesignTokens): string {
  if (node?.type === 'text' && node.typographyTokenId && tokens.typography.some(token => token.id === node.typographyTokenId)) {
    return `var(${cssVar(node.typographyTokenId)}-font-weight)`
  }
  return node?.type === 'text' ? String(node.fontWeight) : 'inherit'
}

function lineHeightCss(node: DesignNode | null, tokens: DesignTokens): string {
  if (node?.type === 'text' && node.typographyTokenId && tokens.typography.some(token => token.id === node.typographyTokenId)) {
    return `var(${cssVar(node.typographyTokenId)}-line-height)`
  }
  return node?.type === 'text' ? String(node.lineHeight) : 'inherit'
}

function colorCss(tokens: DesignTokens, raw: string, tokenId: string | null): string {
  if (tokenId && tokens.colors.some(token => token.id === tokenId)) return `var(${cssVar(tokenId)})`
  return raw || 'transparent'
}

function rule(selector: string, declarations: Record<string, string>): string {
  const body = Object.entries(declarations)
    .filter(([, value]) => value !== '')
    .map(([key, value]) => `  ${key}: ${value};`)
    .join('\n')
  return `${selector} {\n${body}\n}`
}

function uniqueIdentifier(name: string, fallback: string, taken: Set<string>): string {
  const parts = name.split(/[^A-Za-z0-9]+/).filter(Boolean)
  const pascal = parts.map(part => part.charAt(0).toUpperCase() + part.slice(1)).join('')
  const base = pascal && /^[A-Za-z]/.test(pascal) ? pascal : `${fallback}${pascal}`
  let next = base || fallback
  let index = 2
  while (taken.has(next)) {
    next = `${base}${index}`
    index += 1
  }
  taken.add(next)
  return next
}

export function cssVar(id: string): string {
  return `--${id.replace(/[^A-Za-z0-9_-]/g, '')}`
}

export function nodeClass(id: string): string {
  return `n-${id.replace(/[^A-Za-z0-9_-]/g, '')}`
}

function componentClass(id: string): string {
  return `c-${id.replace(/[^A-Za-z0-9_-]/g, '')}`
}

function pageClass(id: string): string {
  return `page-${id.replace(/[^A-Za-z0-9_-]/g, '')}`
}
